-- PostgreSQL (Supabase) baseline: the schema the application uses after mysql/V1 + mysql/V2.
-- Fresh Supabase projects start here; Flyway then applies V3 and later.
--
-- Differences from the MySQL scripts:
--   * ENUM columns are VARCHAR with CHECK constraints.
--   * JSON payload columns are TEXT: the application reads and writes them as strings,
--     and TEXT avoids implicit-cast errors from the JDBC driver.
--   * The unused legacy tables from the original edge-device design (models,
--     model_versions, predictions, device_commands, alerts, system_events) are not created.

CREATE TABLE users (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    first_name      VARCHAR(100) NOT NULL,
    last_name       VARCHAR(100) NOT NULL,
    email           VARCHAR(255) NOT NULL UNIQUE,
    password_hash   VARCHAR(255) NOT NULL,
    role            VARCHAR(20)  NOT NULL DEFAULT 'PATIENT' CHECK (role IN ('PATIENT', 'THERAPIST', 'ADMIN')),
    status          VARCHAR(20)  NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    therapist_id    BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_users_therapist ON users (therapist_id);

CREATE TABLE exercises (
    id                          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name                        VARCHAR(150) NOT NULL,
    description                 TEXT NULL,
    reference_video_path        VARCHAR(500) NULL,
    reference_keypoints_path    VARCHAR(500) NULL,
    match_stability_seconds     NUMERIC(4,2) NOT NULL DEFAULT 1.50,
    analyzer_key                VARCHAR(64) NULL,
    instructions                TEXT NULL,
    camera_setup                VARCHAR(500) NULL,
    body_region                 VARCHAR(50) NULL,
    default_reps                INT NOT NULL DEFAULT 10,
    analysis_config_json        TEXT NULL,
    active                      BOOLEAN NOT NULL DEFAULT TRUE,
    created_at                  TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE devices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    device_id       VARCHAR(64) NOT NULL UNIQUE,
    device_name     VARCHAR(150) NOT NULL,
    api_key_hash    VARCHAR(255) NOT NULL,
    owner_user_id   BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    status          VARCHAR(20) NOT NULL DEFAULT 'ACTIVE' CHECK (status IN ('ACTIVE', 'DISABLED')),
    last_seen_at    TIMESTAMP NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_devices_owner ON devices (owner_user_id);

CREATE TABLE exercise_assignments (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id          BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exercise_id         BIGINT NOT NULL REFERENCES exercises(id),
    assigned_by_id      BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    target_reps         INT NOT NULL,
    sets_per_session    INT NOT NULL DEFAULT 1,
    sessions_per_week   INT NULL,
    notes               VARCHAR(500) NULL,
    active              BOOLEAN NOT NULL DEFAULT TRUE,
    created_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_assign_patient ON exercise_assignments (patient_id);

CREATE TABLE sessions (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id             BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    exercise_id         BIGINT NOT NULL REFERENCES exercises(id),
    device_id           BIGINT NULL REFERENCES devices(id) ON DELETE SET NULL,
    assignment_id       BIGINT NULL REFERENCES exercise_assignments(id) ON DELETE SET NULL,
    client_session_id   VARCHAR(64) NULL,
    rounds_requested    INT NOT NULL,
    rounds_completed    INT NOT NULL DEFAULT 0,
    correct_reps        INT NULL,
    duration_seconds    INT NULL,
    status              VARCHAR(20) NOT NULL DEFAULT 'IN_PROGRESS' CHECK (status IN ('IN_PROGRESS', 'COMPLETED', 'ABORTED')),
    started_at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    ended_at            TIMESTAMP NULL,
    CONSTRAINT uq_session_client UNIQUE (user_id, client_session_id)
);
CREATE INDEX idx_sessions_user ON sessions (user_id);
CREATE INDEX idx_sessions_exercise ON sessions (exercise_id);
CREATE INDEX idx_sessions_assignment ON sessions (assignment_id);

CREATE TABLE session_events (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id          BIGINT NOT NULL REFERENCES sessions(id) ON DELETE CASCADE,
    event_uid           VARCHAR(64) NOT NULL,
    sequence_no         INT NOT NULL,
    event_timestamp     TIMESTAMP(3) NOT NULL,
    joint_name          VARCHAR(50) NULL,
    deviation_value     NUMERIC(6,2) NULL,
    feedback_message    VARCHAR(255) NULL,
    source              VARCHAR(30) NOT NULL DEFAULT 'GEOMETRIC_COMPARISON'
                        CHECK (source IN ('GEOMETRIC_COMPARISON', 'CLASSIFIER', 'ON_DEVICE_RULES')),
    event_type          VARCHAR(30) NULL,
    error_code          VARCHAR(50) NULL,
    rep_number          INT NULL,
    CONSTRAINT uq_event_uid UNIQUE (session_id, event_uid)
);
CREATE INDEX idx_events_session ON session_events (session_id);

CREATE TABLE session_reports (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    session_id              BIGINT NOT NULL UNIQUE REFERENCES sessions(id) ON DELETE CASCADE,
    accuracy_pct            NUMERIC(5,2) NOT NULL,
    total_reps              INT NOT NULL,
    correct_reps            INT NULL,
    duration_seconds        INT NULL,
    common_mistakes_json    TEXT NULL,
    metrics_json            TEXT NULL,
    generated_at            TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE refresh_tokens (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id         BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    token_hash      VARCHAR(64) NOT NULL UNIQUE,     -- SHA-256 hex of the opaque token; the raw token is never stored
    expires_at      TIMESTAMP NOT NULL,
    revoked_at      TIMESTAMP NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_refresh_user ON refresh_tokens (user_id);

