-- PostgreSQL equivalent of mysql/V3__physiotherapist_dashboard.sql (keep them in sync).

ALTER TABLE users
    ADD COLUMN phone VARCHAR(30) NULL,
    ADD COLUMN date_of_birth DATE NULL,
    ADD COLUMN primary_condition VARCHAR(255) NULL,
    ADD COLUMN rehab_status VARCHAR(20) NULL
        CHECK (rehab_status IN ('ASSESSMENT', 'IN_TREATMENT', 'ON_HOLD', 'DISCHARGED'));

UPDATE users SET rehab_status = 'IN_TREATMENT' WHERE role = 'PATIENT';

ALTER TABLE exercise_assignments
    ADD COLUMN status VARCHAR(20) NOT NULL DEFAULT 'ACTIVE'
        CHECK (status IN ('ACTIVE', 'PAUSED', 'DISCONTINUED', 'COMPLETED', 'REPLACED')),
    ADD COLUMN duration_seconds INT NULL CHECK (duration_seconds IS NULL OR duration_seconds >= 0),
    ADD COLUMN rest_seconds INT NULL CHECK (rest_seconds IS NULL OR rest_seconds >= 0),
    ADD COLUMN start_date DATE NULL,
    ADD COLUMN end_date DATE NULL,
    ADD COLUMN difficulty VARCHAR(20) NULL CHECK (difficulty IN ('EASY', 'MODERATE', 'HARD')),
    ADD COLUMN previous_assignment_id BIGINT NULL REFERENCES exercise_assignments(id) ON DELETE SET NULL,
    ADD COLUMN updated_at TIMESTAMP NULL,
    ADD CONSTRAINT chk_assign_dates CHECK (end_date IS NULL OR start_date IS NULL OR end_date >= start_date);

UPDATE exercise_assignments SET status = CASE WHEN active THEN 'ACTIVE' ELSE 'DISCONTINUED' END;

CREATE INDEX idx_assign_patient_status ON exercise_assignments (patient_id, status);
CREATE INDEX idx_sessions_user_started ON sessions (user_id, started_at);

CREATE TABLE therapist_notes (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id      BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_id       BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    note_text       VARCHAR(4000) NOT NULL,
    created_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX idx_notes_patient ON therapist_notes (patient_id, created_at);

CREATE TABLE patient_reports (
    id                      BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    patient_id              BIGINT NOT NULL REFERENCES users(id) ON DELETE CASCADE,
    author_id               BIGINT NULL REFERENCES users(id) ON DELETE SET NULL,
    title                   VARCHAR(200) NULL,
    period_start            DATE NOT NULL,
    period_end              DATE NOT NULL,
    measurements_json       TEXT NOT NULL,
    observations            VARCHAR(4000) NULL,
    recommendations         VARCHAR(4000) NULL,
    exercise_modifications  VARCHAR(4000) NULL,
    follow_up_instructions  VARCHAR(4000) NULL,
    shared_with_patient     BOOLEAN NOT NULL DEFAULT FALSE,
    created_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at              TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    CONSTRAINT chk_report_period CHECK (period_end >= period_start)
);
CREATE INDEX idx_patient_reports_patient ON patient_reports (patient_id, created_at);
